#!/usr/bin/env node
/**
 * Recursively scans images/ssociety-gallery/<category>/... and writes
 * images/ssociety-gallery-manifest.js — a plain script (not JSON) so it
 * can be loaded with a <script> tag and works even when the site is
 * opened straight from disk (file://), where fetch() of local JSON is
 * blocked by the browser.
 *
 * Usage: node scripts/generate-gallery-manifest.js
 *
 * If this prints nothing or errors at all when you run it, your
 * environment likely doesn't have a real Node.js shell behind
 * whatever "run" button you're using — use manifest-builder.html
 * instead (open it in any browser, no terminal needed).
 *
 * To add real screenshots: drop image files into
 * images/ssociety-gallery/<category>/ (make new category folders freely —
 * the scan is fully recursive) and re-run this script. The gallery on
 * project-ssociety.html will pick a random image per category automatically.
 */
try {
    const fs = require("fs");
    const path = require("path");

    const ROOT = path.join(__dirname, "..", "images", "ssociety-gallery");
    const OUT = path.join(__dirname, "..", "images", "ssociety-gallery-manifest.js");
    const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"]);

    console.log("generate-gallery-manifest.js starting...");
    console.log("Looking for images in: " + ROOT);

    if (!fs.existsSync(ROOT)) {
        console.error("ERROR: that folder does not exist. Nothing to scan.");
        console.error("Expected it at: " + ROOT);
        process.exit(1);
    }

    function scan(dir) {
        const manifest = {};

        function walk(current, category) {
            const entries = fs.readdirSync(current, { withFileTypes: true });
            for (const entry of entries) {
                const full = path.join(current, entry.name);
                if (entry.isDirectory()) {
                    // Leaf category = the deepest folder name containing images
                    walk(full, entry.name);
                } else if (IMAGE_EXT.has(path.extname(entry.name).toLowerCase())) {
                    const rel = path.relative(path.join(__dirname, ".."), full).split(path.sep).join("/");
                    if (!manifest[category]) manifest[category] = [];
                    manifest[category].push(rel);
                }
            }
        }

        const topEntries = fs.readdirSync(dir, { withFileTypes: true });
        for (const entry of topEntries) {
            if (entry.isDirectory()) {
                walk(path.join(dir, entry.name), entry.name);
            }
        }
        return manifest;
    }

    const manifest = scan(ROOT);
    const categoryCount = Object.keys(manifest).length;
    const imageCount = Object.values(manifest).reduce((sum, arr) => sum + arr.length, 0);

    if (imageCount === 0) {
        console.warn("WARNING: found 0 images. Check that files sit directly");
        console.warn("inside category folders, e.g. images/ssociety-gallery/dashboard/shot1.jpg");
        console.warn("(supported: .jpg .jpeg .png .webp .gif)");
    }

    const banner =
        "// AUTO-GENERATED by scripts/generate-gallery-manifest.js — do not hand-edit.\n" +
        "// Re-run: node scripts/generate-gallery-manifest.js\n";
    const body = "window.SSOCIETY_GALLERY_MANIFEST = " + JSON.stringify(manifest, null, 2) + ";\n";
    fs.writeFileSync(OUT, banner + body);

    console.log("Wrote " + OUT);
    console.log(categoryCount + " categories, " + imageCount + " images total.");
    console.log("Done. Refresh project-ssociety.html to see the changes.");
} catch (err) {
    console.error("generate-gallery-manifest.js FAILED:");
    console.error(err);
    process.exitCode = 1;
}
